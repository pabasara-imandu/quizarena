/**
 * Deterministic, seedable PRNG helpers.
 *
 * Why deterministic? Each player gets their own scrambled answer order, but the
 * server must be able to reproduce that order on demand (reconnects, late
 * joins, reveals) without storing a permutation per player per question.
 * Seeding on `playerId:questionId` makes the shuffle stable and free.
 */

/** xmur3 string hash -> 32-bit seed */
export function hashSeed(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return () => {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return h >>> 0;
  };
}

/** mulberry32 PRNG */
export function mulberry32(a) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher-Yates using a seeded PRNG. Returns a new array. */
export function seededShuffle(arr, seedString) {
  const rand = mulberry32(hashSeed(seedString)());
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
